// Builds the development Telegram emulator (WP-21, TMA-045) into public/__dev/telegram-emulator.js for `next dev`;
// `--clean` deletes it before `next build`, so production output never contains it (WP-33 checks). No bundler: the
// three sources are erasable TypeScript, so Node's type stripping plus dropping their import and export keywords
// gives one classic script.
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import module from "node:module";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

const dir = import.meta.dirname;
const sources = [
  join(dir, "../../packages/testing/src/initData.ts"),
  join(dir, "../../packages/testing/src/fakeTelegram.ts"),
  join(dir, "telegram-emulator.ts"),
];
export const FILE_NAME = "telegram-emulator.js";
const defaultTarget = join(dir, "../public/__dev");

/** The emulator as one script: the double of @homi/testing, then the emulator itself, in one function scope. */
export function buildEmulator() {
  // Type stripping is still marked experimental in Node 26; its warning is noise here.
  const emit = process.emitWarning;
  process.emitWarning = () => undefined;
  try {
    const body = sources
      .map((file) => module.stripTypeScriptTypes(readFileSync(file, "utf8"), { mode: "strip" }))
      .map((code) =>
        code
          .replace(/^import\b[\s\S]*?\bfrom\s+["'][^"']+["'];?[ \t]*$/gm, "")
          .replace(/^export\s+(?=(?:async\s+)?function\b|const\b|let\b|class\b)/gm, ""),
      )
      .join("\n");
    return `/* Generated by dev/build.mjs for next dev only. Not part of any build. */\n(function () {\n"use strict";\n${body}\n})();\n`;
  } finally {
    process.emitWarning = emit;
  }
}

export function writeEmulator(target = defaultTarget) {
  mkdirSync(target, { recursive: true });
  const file = join(target, FILE_NAME);
  writeFileSync(file, buildEmulator());
  return file;
}

export function cleanEmulator(target = defaultTarget) {
  rmSync(join(target, FILE_NAME), { force: true });
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  if (process.argv.includes("--clean")) {
    cleanEmulator();
  } else {
    writeEmulator();
  }
}
