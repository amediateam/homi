// Writes boot/inline.generated.ts from boot/stubs.js and boot/boot.js (WP-21). Runs from `predev` and `prebuild`;
// the output is committed, so lint and typecheck resolve it without a build, and tests/boot/boot.test.ts fails
// when it is stale. No bundler touches the two scripts: the root layout inlines their text as written.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = import.meta.dirname;
const text = (name) => readFileSync(join(dir, name), "utf8");

const output = `// Generated by boot/build.mjs from boot/stubs.js and boot/boot.js. Do not edit.

export const BOOT_STUBS = ${JSON.stringify(text("stubs.js"))};

export const BOOT_SCRIPT = ${JSON.stringify(text("boot.js"))};
`;

const target = join(dir, "inline.generated.ts");
let current = "";
try {
  current = readFileSync(target, "utf8");
} catch {
  // First run.
}
if (current !== output) {
  writeFileSync(target, output);
}
